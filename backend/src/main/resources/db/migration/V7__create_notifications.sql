CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    activity_event_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_event FOREIGN KEY (activity_event_id) REFERENCES activity_events(id) ON DELETE CASCADE,
    CONSTRAINT uq_notification_user_event UNIQUE (user_id, activity_event_id)
);
CREATE INDEX idx_notifications_user_created ON notifications(user_id, created_at DESC);
